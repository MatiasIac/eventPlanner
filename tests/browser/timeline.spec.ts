test('polling pauses while idle, offline or hidden and resumes on interaction', async ({ page }) => {
  await page.clock.install();
  await join(page, 'Polling participant'); await expect(page.getByRole('heading', { name: 'Our ceremony', exact: true })).toBeVisible();
  let requests = 0; page.on('request', request => { if (request.url().endsWith('/api/timeline')) requests++; });
  await page.clock.fastForward(31000); await expect.poll(() => requests).toBeGreaterThan(0);
  await page.clock.fastForward(125000); await page.waitForTimeout(100); const idleCount = requests;
  await page.clock.fastForward(61000); expect(requests).toBe(idleCount);
  await page.locator('h1').click(); await expect.poll(() => requests).toBeGreaterThan(idleCount);
  await page.evaluate(() => { Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'hidden' }); document.dispatchEvent(new Event('visibilitychange')); });
  await page.waitForTimeout(100); const hiddenCount = requests; await page.clock.fastForward(61000); expect(requests).toBe(hiddenCount);
  await page.evaluate(() => { Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'visible' }); document.dispatchEvent(new Event('visibilitychange')); });
  await expect.poll(() => requests).toBeGreaterThan(hiddenCount);
  await page.evaluate(() => { Object.defineProperty(navigator, 'onLine', { configurable: true, value: false }); window.dispatchEvent(new Event('offline')); });
  await page.waitForTimeout(100); const offlineCount = requests; await page.clock.fastForward(61000); expect(requests).toBe(offlineCount);
  await expect(page.getByText('Offline - showing the saved timeline', { exact: false })).toBeVisible();
});

