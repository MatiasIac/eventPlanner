CREATE TABLE wedding (
  id integer PRIMARY KEY CHECK (id = 1), title text NOT NULL, date date,
  venue text NOT NULL DEFAULT '', timezone text NOT NULL DEFAULT 'Pacific/Auckland',
  revision integer NOT NULL DEFAULT 1, demonstration boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now()
);
