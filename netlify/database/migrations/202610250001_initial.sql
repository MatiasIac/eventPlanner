CREATE TABLE participants (
  id uuid PRIMARY KEY, display_name varchar(80) NOT NULL,
  role text NOT NULL CHECK (role IN ('participant', 'organiser')),
  return_hash text UNIQUE, revoked boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE sessions (
  token_hash text PRIMARY KEY, participant_id uuid NOT NULL REFERENCES participants,
  expires_at timestamptz NOT NULL, revoked boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sessions_participant ON sessions(participant_id);
CREATE TABLE images (
  id uuid PRIMARY KEY, storage_key text UNIQUE NOT NULL, namespace text NOT NULL,
  content_type text NOT NULL, size integer NOT NULL CHECK (size > 0 AND size <= 2097152),
  alt text NOT NULL, uploader_id uuid NOT NULL REFERENCES participants,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE activities (
  id uuid PRIMARY KEY, wedding_id integer NOT NULL DEFAULT 1 REFERENCES wedding,
  title varchar(120) NOT NULL CHECK (length(title) > 0), description varchar(1200) NOT NULL DEFAULT '',
  start_time time, day_offset smallint NOT NULL DEFAULT 0 CHECK (day_offset IN (0,1)),
  end_time time, end_day_offset smallint NOT NULL DEFAULT 0 CHECK (end_day_offset IN (0,1)),
  location_note varchar(240) NOT NULL DEFAULT '', illustration text NOT NULL DEFAULT 'leaf',
  image_id uuid REFERENCES images, image_alt varchar(240) NOT NULL DEFAULT '',
  sort_order bigint GENERATED BY DEFAULT AS IDENTITY,
  creator_id uuid NOT NULL REFERENCES participants, revision integer NOT NULL DEFAULT 1,
  archived boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (end_time IS NULL OR (start_time IS NOT NULL AND (end_day_offset > day_offset OR (end_day_offset = day_offset AND end_time > start_time))))
);
CREATE INDEX activity_schedule ON activities(archived, day_offset, start_time, sort_order);
CREATE TABLE jobs (
  id uuid PRIMARY KEY, activity_id uuid NOT NULL REFERENCES activities,
  title varchar(120) NOT NULL CHECK (length(title) > 0), instructions varchar(1200) NOT NULL DEFAULT '',
  capacity integer NOT NULL DEFAULT 1 CHECK (capacity BETWEEN 1 AND 100),
  creator_id uuid NOT NULL REFERENCES participants, revision integer NOT NULL DEFAULT 1,
  archived boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX jobs_activity ON jobs(activity_id);
CREATE TABLE assignments (
  id uuid PRIMARY KEY, job_id uuid NOT NULL REFERENCES jobs,
  participant_id uuid REFERENCES participants, nominee_name varchar(80),
  manager_id uuid NOT NULL REFERENCES participants, active boolean NOT NULL DEFAULT true,
  revision integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((participant_id IS NOT NULL AND nominee_name IS NULL AND manager_id = participant_id) OR (participant_id IS NULL AND length(nominee_name) > 0))
);
CREATE UNIQUE INDEX one_active_self_assignment ON assignments(job_id, participant_id) WHERE active AND participant_id IS NOT NULL;
CREATE INDEX assignments_job ON assignments(job_id, active);
CREATE INDEX assignments_manager ON assignments(manager_id);
CREATE TABLE idempotency (
  participant_id uuid NOT NULL REFERENCES participants, request_id uuid NOT NULL,
  fingerprint text NOT NULL, response jsonb NOT NULL, created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(participant_id, request_id)
);
CREATE TABLE rate_limits (
  key text PRIMARY KEY, count integer NOT NULL, expires_at timestamptz NOT NULL
);
